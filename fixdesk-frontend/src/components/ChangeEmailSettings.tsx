import React, { useState } from 'react';
import {
    Box,
    Card,
    CardContent,
    Typography,
    TextField,
    Button,
    Alert,
    CircularProgress,
    Dialog,
    DialogTitle,
    DialogContent,
    DialogActions
} from '@mui/material';
import EmailIcon from '@mui/icons-material/Email';
import WarningAmberIcon from '@mui/icons-material/WarningAmber';
import axios from 'axios';

interface ChangeEmailSettingsProps {
    currentEmail: string;
    token: string;
    onEmailChanged?: () => void;
}

const ChangeEmailSettings: React.FC<ChangeEmailSettingsProps> = ({ currentEmail, token, onEmailChanged }) => {
    const [newEmail, setNewEmail] = useState('');
    const [verificationCode, setVerificationCode] = useState('');
    const [step, setStep] = useState<'input' | 'verify'>('input');
    const [loading, setLoading] = useState(false);
    const [error, setError] = useState('');
    const [success, setSuccess] = useState('');
    const [dialogOpen, setDialogOpen] = useState(false);

    const backendUrl = import.meta.env.VITE_BACKEND_URL || 'http://localhost:3000';
    
    const isAutoGeneratedEmail = currentEmail.endsWith('@fixdesk.local');

    const handleRequestChange = async () => {
        if (!newEmail || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(newEmail)) {
            setError('Введите корректный email');
            return;
        }

        setLoading(true);
        setError('');
        setSuccess('');

        try {
            const response = await axios.post(
                `${backendUrl}/auth/change-email/request`,
                { newEmail },
                { headers: { Authorization: `Bearer ${token}` } }
            );

            if (response.data.success) {
                setSuccess(response.data.message);
                setStep('verify');
            }
        } catch (err: any) {
            setError(err.response?.data?.message || 'Ошибка отправки кода');
        } finally {
            setLoading(false);
        }
    };

    const handleVerifyCode = async () => {
        if (!verificationCode || verificationCode.length !== 6) {
            setError('Введите 6-значный код');
            return;
        }

        setLoading(true);
        setError('');

        try {
            const response = await axios.post(
                `${backendUrl}/auth/change-email/verify`,
                { code: verificationCode },
                { headers: { Authorization: `Bearer ${token}` } }
            );

            if (response.data.success) {
                setSuccess(response.data.message);
                setDialogOpen(false);
                setStep('input');
                setNewEmail('');
                setVerificationCode('');
                
                if (onEmailChanged) {
                    onEmailChanged();
                }
            }
        } catch (err: any) {
            setError(err.response?.data?.message || 'Ошибка проверки кода');
        } finally {
            setLoading(false);
        }
    };

    const handleOpenDialog = () => {
        setDialogOpen(true);
        setError('');
        setSuccess('');
        setStep('input');
        setNewEmail('');
        setVerificationCode('');
    };

    const handleCloseDialog = () => {
        if (!loading) {
            setDialogOpen(false);
            setError('');
            setSuccess('');
            setStep('input');
            setNewEmail('');
            setVerificationCode('');
        }
    };

    return (
        <Box>
            <Typography variant="h6" gutterBottom sx={{ color: '#fff' }}>
                Email
            </Typography>

            {isAutoGeneratedEmail && (
                <Alert 
                    severity="warning" 
                    icon={<WarningAmberIcon />}
                    sx={{ mb: 2 }}
                >
                    <Typography variant="body2">
                        Вы используете автоматический email. Привяжите свой реальный email для получения уведомлений.
                    </Typography>
                </Alert>
            )}

            {success && !dialogOpen && (
                <Alert severity="success" sx={{ mb: 2 }} onClose={() => setSuccess('')}>
                    {success}
                </Alert>
            )}

            <Card sx={{ bgcolor: '#212134' }}>
                <CardContent>
                    <Box sx={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between' }}>
                        <Box sx={{ display: 'flex', alignItems: 'center', gap: 2 }}>
                            <EmailIcon sx={{ color: '#4945ff' }} />
                            <Box>
                                <Typography variant="body2" sx={{ color: '#6b6f7e' }}>
                                    Текущий email
                                </Typography>
                                <Typography variant="body1" sx={{ color: '#fff', fontWeight: 500 }}>
                                    {currentEmail}
                                </Typography>
                                {isAutoGeneratedEmail && (
                                    <Typography variant="caption" sx={{ color: '#ff6b6b' }}>
                                        (автоматический)
                                    </Typography>
                                )}
                            </Box>
                        </Box>
                        <Button
                            variant="outlined"
                            onClick={handleOpenDialog}
                            sx={{
                                borderColor: '#4a4a6a',
                                color: '#fff',
                                textTransform: 'none',
                                '&:hover': {
                                    borderColor: '#4945ff',
                                    bgcolor: 'rgba(73, 69, 255, 0.08)'
                                }
                            }}
                        >
                            Изменить email
                        </Button>
                    </Box>
                </CardContent>
            </Card>

            <Dialog 
                open={dialogOpen} 
                onClose={handleCloseDialog}
                maxWidth="sm"
                fullWidth
            >
                <DialogTitle sx={{ bgcolor: '#16161a', color: '#fff' }}>
                    {step === 'input' ? 'Изменить email' : 'Подтверждение email'}
                </DialogTitle>
                <DialogContent sx={{ bgcolor: '#16161a', pt: 3 }}>
                    {error && (
                        <Alert severity="error" sx={{ mb: 2 }} onClose={() => setError('')}>
                            {error}
                        </Alert>
                    )}

                    {success && (
                        <Alert severity="success" sx={{ mb: 2 }}>
                            {success}
                        </Alert>
                    )}

                    {step === 'input' ? (
                        <>
                            <Typography variant="body2" sx={{ mb: 2, color: '#a5a5ba' }}>
                                Введите новый email. Мы отправим на него код подтверждения.
                            </Typography>
                            <TextField
                                fullWidth
                                label="Новый email"
                                type="email"
                                value={newEmail}
                                onChange={(e) => setNewEmail(e.target.value)}
                                disabled={loading}
                                autoFocus
                                sx={{
                                    '& .MuiOutlinedInput-root': {
                                        bgcolor: '#212134',
                                        '& fieldset': {
                                            borderColor: '#32324d'
                                        },
                                        '&:hover fieldset': {
                                            borderColor: '#4a4a6a'
                                        }
                                    },
                                    '& .MuiInputLabel-root': {
                                        color: '#a5a5ba'
                                    },
                                    '& .MuiOutlinedInput-input': {
                                        color: '#fff'
                                    }
                                }}
                            />
                        </>
                    ) : (
                        <>
                            <Typography variant="body2" sx={{ mb: 2, color: '#a5a5ba' }}>
                                Мы отправили 6-значный код на <strong>{newEmail}</strong>. Введите его ниже.
                            </Typography>
                            <TextField
                                fullWidth
                                label="Код подтверждения"
                                value={verificationCode}
                                onChange={(e) => setVerificationCode(e.target.value.replace(/\D/g, '').slice(0, 6))}
                                disabled={loading}
                                autoFocus
                                inputProps={{ maxLength: 6, style: { textAlign: 'center', fontSize: '24px', letterSpacing: '10px' } }}
                                sx={{
                                    '& .MuiOutlinedInput-root': {
                                        bgcolor: '#212134',
                                        '& fieldset': {
                                            borderColor: '#32324d'
                                        },
                                        '&:hover fieldset': {
                                            borderColor: '#4a4a6a'
                                        }
                                    },
                                    '& .MuiInputLabel-root': {
                                        color: '#a5a5ba'
                                    },
                                    '& .MuiOutlinedInput-input': {
                                        color: '#fff'
                                    }
                                }}
                            />
                        </>
                    )}
                </DialogContent>
                <DialogActions sx={{ bgcolor: '#16161a', p: 2 }}>
                    <Button 
                        onClick={handleCloseDialog} 
                        disabled={loading}
                        sx={{ color: '#6b6f7e' }}
                    >
                        Отмена
                    </Button>
                    {step === 'verify' && (
                        <Button 
                            onClick={() => setStep('input')} 
                            disabled={loading}
                            sx={{ color: '#4945ff' }}
                        >
                            Назад
                        </Button>
                    )}
                    <Button
                        onClick={step === 'input' ? handleRequestChange : handleVerifyCode}
                        variant="contained"
                        disabled={loading || (step === 'input' ? !newEmail : verificationCode.length !== 6)}
                        sx={{
                            bgcolor: '#4945ff',
                            '&:hover': { bgcolor: '#7b79ff' },
                            '&:disabled': {
                                bgcolor: '#32324d',
                                color: '#6b6f7e'
                            }
                        }}
                    >
                        {loading ? <CircularProgress size={24} /> : (step === 'input' ? 'Отправить код' : 'Подтвердить')}
                    </Button>
                </DialogActions>
            </Dialog>
        </Box>
    );
};

export default ChangeEmailSettings;
